package com.yg.kotlinks.pages

/** Escapes a value for use in HTML text and quoted attribute values. */
internal fun escapeHtml(value: String): String = buildString(value.length) {
    value.forEach { c ->
        when (c) {
            '&' -> append("&amp;")
            '<' -> append("&lt;")
            '>' -> append("&gt;")
            '"' -> append("&quot;")
            '\'' -> append("&#39;")
            else -> append(c)
        }
    }
}

/** Escapes a value as a JSON string literal (including the surrounding quotes). */
internal fun jsonString(value: String): String = buildString(value.length + 2) {
    append('"')
    value.forEach { c ->
        when (c) {
            '"' -> append("\\\"")
            '\\' -> append("\\\\")
            '\n' -> append("\\n")
            '\r' -> append("\\r")
            '\t' -> append("\\t")
            else -> if (c < ' ') {
                append("\\u%04x".format(c.code))
            } else {
                append(c)
            }
        }
    }
    append('"')
}
